// VCSL (Versilian Community Sample Library) and VSCO 2 CE ship samples without SFZ mappings for
// many instruments, but the file names carry note, dynamic and round robin. This writes a plain
// SFZ for one instrument folder: first round robin only, dynamics stacked as velocity layers.
// The key ranges between sampled notes are filled in later by the build (respanKeys).

const PC = { C: 0, 'C#': 1, DB: 1, D: 2, 'D#': 3, EB: 3, E: 4, F: 5, 'F#': 6, GB: 6, G: 7, 'G#': 8, AB: 8, A: 9, 'A#': 10, BB: 10, B: 11 };

// "A#0" / "bb3" -> MIDI; c3: Yamaha naming where C3 is middle C (60)
export function noteOf(name, c3 = false) {
  const m = /^([A-Ga-g](?:#|b)?)(-?\d)$/.exec(name);
  return 12 * (+m[2] + 1) + PC[m[1].toUpperCase()] + (c3 ? 12 : 0);
}

function pick(blobs, dir, re, opts) {
  const out = [];
  const seen = new Set();
  for (const b of blobs) {
    if (!b.path.startsWith(dir)) continue;
    const m = re.exec(b.path.slice(dir.length));
    if (!m) continue;
    const layer = m[2] == null ? 0 : opts.layers ? opts.layers.indexOf(m[2]) : +m[2] - 1;
    if (layer < 0) continue;
    const note = noteOf(m[1], opts.c3) + (opts.shift || 0);
    if (opts.lo != null && note < opts.lo) continue;
    if (opts.hi != null && note > opts.hi) continue;
    const key = `${note}/${layer}`;
    if (seen.has(key)) continue; // a second take of the same note: keep the first
    seen.add(key);
    out.push({ path: b.path, note, layer });
  }
  return out;
}

function write(picks, opts, name) {
  // every part of a stacked instrument must have the same number of layers (checked here), so
  // the velocity bands line up and the build can fill the keys between parts within each band
  const counts = new Set(picks.map((p) => p.layerCount));
  if (counts.size > 1) throw new Error(`${name}: parts have different layer counts ${[...counts]}`);
  const count = picks[0]?.layerCount || 1;
  const band = (i) => [Math.round((i * 127) / count) + 1, Math.round(((i + 1) * 127) / count)];
  let text = `// generated by tools/vcsl-map.mjs
<control>
default_path=../
<global>
ampeg_release=${opts.release ?? 0.4}
`;
  for (const p of picks.sort((a, b) => a.layer - b.layer || a.note - b.note)) {
    const [lv, hv] = band(p.layer);
    // sample last: VCSL paths have spaces and commas
    text += `<region> lokey=${p.note} hikey=${p.note} pitch_keycenter=${p.note} lovel=${lv} hivel=${hv} sample=${p.path}
`;
  }
  return [{ name: `_melofi/${name}.sfz`, text }];
}

function finish(picks) {
  const layers = [...new Set(picks.map((p) => p.layer))].sort((a, b) => a - b);
  // renumber to 0..n-1 (a library may skip a dynamic)
  return picks.map((p) => ({ ...p, layer: layers.indexOf(p.layer), layerCount: layers.length }));
}

// dir: folder inside the repository; re: file-name pattern with (note) and optional (layer)
// opts.layers: layer names quietest first (else numeric layer captures, 1 = quietest)
// opts.shift: semitones to add when the samples sound away from their names
export function vcslMap(blobs, dir, re, opts = {}) {
  const picks = finish(pick(blobs, dir, re, opts));
  return write(picks, opts, opts.file || dir.split('/').filter(Boolean).pop().replace(/[^a-z0-9]+/gi, '_').toLowerCase());
}

// Several folders stacked across the keyboard into one instrument (a string section built from
// cellos, violas and violins). parts: [{ dir, re, lo, hi, c3, shift, layers }]
export function vcslMulti(blobs, parts, opts = {}) {
  const all = parts.flatMap((p) => finish(pick(blobs, p.dir, p.re, { c3: opts.c3, ...p })));
  return write(all, opts, opts.file);
}

// Sound effects with no pitch (a siren, waves, a cymbal swell): the same recording on every key,
// played as recorded wherever it is pressed. files: names in `dir`, quietest first (velocity layers).
export function oneShot(blobs, dir, files, opts = {}) {
  const paths = files.map((f) => blobs.find((b) => b.path === dir + f)?.path).filter(Boolean);
  if (!paths.length) throw new Error(`${opts.file}: no samples in ${dir}`);
  let text = `// generated by tools/vcsl-map.mjs\n<control>\ndefault_path=../\n<global>\nampeg_release=${opts.release ?? 0.4}\n`;
  paths.forEach((p, i) => {
    const lv = Math.round((i * 127) / paths.length) + 1, hv = Math.round(((i + 1) * 127) / paths.length);
    for (let k = opts.lo ?? 0; k <= (opts.hi ?? 127); k++) text += `<region> lokey=${k} hikey=${k} pitch_keycenter=${k} lovel=${lv} hivel=${hv} sample=${p}\n`;
  });
  return [{ name: `_melofi/${opts.file}.sfz`, text }];
}

// One sample per key for percussion: entries [{ key, dir, re }] where re may capture (layer)
export function kitMap(blobs, entries, opts = {}) {
  let text = `// generated by tools/vcsl-map.mjs\n<control>\ndefault_path=../\n<global>\nampeg_release=${opts.release ?? 0.3}\n`;
  for (const e of entries) {
    const hits = [];
    for (const b of blobs) {
      if (!b.path.startsWith(e.dir)) continue;
      const m = e.re.exec(b.path.slice(e.dir.length));
      if (!m) continue;
      const layer = m[1] == null ? 0 : e.layers ? e.layers.indexOf(m[1]) : +m[1] - 1;
      if (layer < 0 || hits.some((h) => h.layer === layer)) continue;
      hits.push({ path: b.path, layer });
    }
    hits.sort((a, b) => a.layer - b.layer);
    hits.forEach((h, i) => {
      const lv = Math.round((i * 127) / hits.length) + 1, hv = Math.round(((i + 1) * 127) / hits.length);
      text += `<region> lokey=${e.key} hikey=${e.key} pitch_keycenter=${e.key} lovel=${lv} hivel=${hv}${e.gain ? ` volume=${e.gain}` : ''} sample=${h.path}\n`;
    });
  }
  return [{ name: `_melofi/${opts.file}.sfz`, text }];
}
