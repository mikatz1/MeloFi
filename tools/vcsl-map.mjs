// VCSL (Versilian Community Sample Library) ships samples without SFZ mappings for many
// instruments, but the file names carry note, dynamic and round robin. This writes a plain SFZ
// for one instrument folder: first round robin only, dynamics stacked as velocity layers.
// The key ranges between sampled notes are filled in later by the build (respanKeys).

const PC = { C: 0, 'C#': 1, D: 2, 'D#': 3, E: 4, F: 5, 'F#': 6, G: 7, 'G#': 8, A: 9, 'A#': 10, B: 11 };

// "A#0" -> MIDI; c3: Yamaha naming where C3 is middle C (60)
export function noteOf(name, c3 = false) {
  const m = /^([A-G]#?)(-?\d)$/.exec(name);
  return 12 * (+m[2] + 1) + PC[m[1]] + (c3 ? 12 : 0);
}

// dir: folder inside the repository; re: file-name pattern with (note) and optional (layer)
// opts.layers: layer names quietest first (else numeric layer captures, 1 = quietest)
// opts.shift: semitones to add when the samples sound away from their names
export function vcslMap(blobs, dir, re, opts = {}) {
  const picks = [];
  for (const b of blobs) {
    if (!b.path.startsWith(dir)) continue;
    const m = re.exec(b.path.slice(dir.length));
    if (!m) continue;
    const layer = m[2] == null ? 0 : opts.layers ? opts.layers.indexOf(m[2]) : +m[2] - 1;
    if (layer < 0) continue;
    picks.push({ path: b.path, note: noteOf(m[1], opts.c3) + (opts.shift || 0), layer });
  }
  const layers = [...new Set(picks.map((p) => p.layer))].sort((a, b) => a - b);
  const band = (i) => [Math.round((i * 127) / layers.length) + 1, Math.round(((i + 1) * 127) / layers.length)];
  let text = `// generated by tools/vcsl-map.mjs from ${dir}\n<control>\ndefault_path=../\n<global>\nampeg_release=${opts.release ?? 0.4}\n`;
  for (const p of picks.sort((a, b) => a.layer - b.layer || a.note - b.note)) {
    const [lv, hv] = band(layers.indexOf(p.layer));
    // sample last: VCSL paths have spaces and commas
    text += `<region> lokey=${p.note} hikey=${p.note} pitch_keycenter=${p.note} lovel=${lv} hivel=${hv} sample=${p.path}\n`;
  }
  const name = '_melofi/' + (opts.file || dir.split('/').filter(Boolean).pop().replace(/[^a-z0-9]+/gi, '_').toLowerCase()) + '.sfz';
  return [{ name, text }];
}
