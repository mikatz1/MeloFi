  mediaPickFiles: (opts) => ipcRenderer.invoke('media:pickFiles', opts),
  mediaPickFolder: () => ipcRenderer.invoke('media:pickFolder'),
  mediaAllowRoots: (list) => ipcRenderer.invoke('media:allowRoots', list),
