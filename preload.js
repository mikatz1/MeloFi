  loadSettings: () => ipcRenderer.invoke('settings:load'),
  saveSettings: (s) => ipcRenderer.invoke('settings:save', s),
  onSettingsChanged: (cb) => ipcRenderer.on('settings:changed', (_e, p) => cb(p)),
